function scoreText(text, weightFactor) {
  const scores = new Map();
  for (const [category, patterns] of RULES) {
    let score = 0;
    for (const [pattern, weight] of patterns) {
      if (pattern.test(text)) score += weight * weightFactor;
    }
    scores.set(category, score);
  }
  return scores;
}

function classifyDeal({ title = '', description = '' } = {}) {
  const titleScores = scoreText(String(title), 1);
  const descriptionScores = scoreText(String(description), 0.65);
  let bestCategory = '기타';
  let bestScore = 0;

  for (const [category] of RULES) {
    const titleScore = titleScores.get(category);
    if (titleScore > bestScore) {
      bestCategory = category;
      bestScore = titleScore;
    }
  }
  if (bestScore >= 4) return bestCategory;

  bestCategory = '기타';
  bestScore = 0;

  for (const [category] of RULES) {
    const score = titleScores.get(category) + descriptionScores.get(category);
    if (score > bestScore) {
      bestCategory = category;
      bestScore = score;
    }
  }
  return bestScore >= 2.5 ? bestCategory : '기타';
}

function isCategory(value) {
  return CATEGORIES.includes(value);
}

module.exports = { CATEGORIES, classifyDeal, isCategory };
